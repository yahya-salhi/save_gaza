/**
 * Gaza governorate boundaries — simplified static GeoJSON (Slice 4.1).
 *
 * Five governorates, north to south: North Gaza, Gaza, Deir al-Balah,
 * Khan Younis, Rafah. Shapes derived from GADM v4.1 (gadm41_PSE_2)
 * admin boundaries, simplified and corner-smoothed — accurate enough
 * for governorate selection at map zoom, tiny enough to serve whole with
 * a 24h cache. Precise OSM-derived shapes are explicitly deferred.
 */

export interface GazaBoundaryProperties {
  id: string;
  name: string;
  sortOrder: number;
}

export interface GazaBoundaryFeature {
  type: "Feature";
  id: string;
  properties: GazaBoundaryProperties;
  geometry: {
    type: "Polygon";
    coordinates: Array<Array<[number, number]>>;
  };
}

export interface GazaBoundariesCollection {
  type: "FeatureCollection";
  features: GazaBoundaryFeature[];
}

function feature(
  id: string,
  name: string,
  sortOrder: number,
  ring: Array<[number, number]>,
): GazaBoundaryFeature {
  return {
    type: "Feature",
    id,
    properties: { id, name, sortOrder },
    geometry: { type: "Polygon", coordinates: [ring] },
  };
}

